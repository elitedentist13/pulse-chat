export type Locale = "en" | "zh-Hant" | "zh-Hans"

export const LOCALES: { id: Locale; short: string; native: string }[] = [
  { id: "en", short: "EN", native: "English" },
  { id: "zh-Hant", short: "繁", native: "繁體中文" },
  { id: "zh-Hans", short: "简", native: "简体中文" },
]

export const LOCALE_STORAGE_KEY = "kith-locale"

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "zh-Hant" || value === "zh-Hans"
}

export function localeTag(locale: Locale) {
  if (locale === "zh-Hant") return "zh-Hant"
  if (locale === "zh-Hans") return "zh-Hans"
  return "en"
}

export function guessLocale(language = ""): Locale {
  const tag = language.toLowerCase()
  if (tag.startsWith("zh-hant") || tag.startsWith("zh-tw") || tag.startsWith("zh-hk") || tag.startsWith("zh-mo")) {
    return "zh-Hant"
  }
  if (tag.startsWith("zh")) return "zh-Hans"
  return "en"
}

