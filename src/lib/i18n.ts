export const dictionaries: Record<Locale, Record<keyof typeof en, string>> = {
  en,
  "zh-Hant": zhHant,
  "zh-Hans": zhHans,
}

export type MessageKey = keyof typeof en

export type Translate = (
  key: MessageKey,
  vars?: Record<string, string | number>
) => string

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
) {
  let text = dictionaries[locale][key] ?? en[key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

export function topicKeys(topic: "craft" | "body" | "kin" | "work"): {
  label: MessageKey
  line: MessageKey
} {
  if (topic === "craft") return { label: "topicCraft", line: "topicCraftLine" }
  if (topic === "body") return { label: "topicBody", line: "topicBodyLine" }
  if (topic === "kin") return { label: "topicKin", line: "topicKinLine" }
  return { label: "topicWork", line: "topicWorkLine" }
}
